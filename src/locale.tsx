export function translate(text: string, language: Language) {
  return language === 'fil' ? filipino[text] ?? text : text
}

interface LocaleContextValue {
  language: Language
  setLanguage: (language: Language) => boolean
  translate: (text: string) => string
  storageError: string | null
}

const LocaleContext = createContext<LocaleContextValue>({
  language: 'en',
  setLanguage: () => true,
  translate: (text) => text,
  storageError: null,
})

function readLanguage() {
  try {
    return { language: localStorage.getItem(languageStorageKey) === 'fil' ? 'fil' as const : 'en' as const, error: null }
  } catch {
    return { language: 'en' as const, error: 'Language preference could not be read from this device.' }
  }
}

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [initialLanguage] = useState(readLanguage)
  const [language, setCurrentLanguage] = useState<Language>(initialLanguage.language)
  const [storageError, setStorageError] = useState<string | null>(initialLanguage.error)

  useEffect(() => {
    document.documentElement.lang = language === 'fil' ? 'fil' : 'en'
  }, [language])

  function setLanguage(nextLanguage: Language) {
    try {
      if (nextLanguage === 'en') localStorage.removeItem(languageStorageKey)
      else localStorage.setItem(languageStorageKey, nextLanguage)
      setCurrentLanguage(nextLanguage)
      setStorageError(null)
      return true
    } catch {
      setStorageError('Language could not be saved on this device.')
      return false
    }
  }

  const value = useMemo<LocaleContextValue>(() => ({
    language,
    setLanguage,
    translate: (text) => translate(text, language),
    storageError,
  }), [language, storageError])

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>
}

export function useLocale() {
  return useContext(LocaleContext)
}
